//! TypeScript generation (ts-rs). Output: `apps/desktop/src/lib/api/generated/`.
//!
//! * one `<Type>.ts` per exported type (ts-rs),
//! * `methods.ts`: `Methods` map `name → {kind, request, response}` for a typed `invoke`,
//! * `index.ts`: re-exports everything.
//!
//! Generation is deterministic; CI runs `gen-ts --check` (and `cargo test` runs the same check)
//! so a Rust DTO change without regenerating fails the build, and a regenerated DTO change breaks
//! `pnpm check` in the frontend.

use crate::method::MethodKind;
use crate::v1;
use std::collections::BTreeSet;
use std::fs;
use std::io;
use std::path::{Path, PathBuf};
use ts_rs::{Config, TS};

/// Files in the output directory that are not generated and must be preserved.
const HAND_WRITTEN: &[&str] = &["README.md"];

/// Default output directory, relative to the workspace root.
pub const DEFAULT_OUT_DIR: &str = "apps/desktop/src/lib/api/generated";

/// Workspace root (two levels above this crate's manifest).
pub fn workspace_root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("../..")
        .components()
        .collect()
}

/// TS generation error.
#[derive(Debug, thiserror::Error)]
pub enum GenError {
    /// ts-rs failed.
    #[error("ts-rs export failed: {0}")]
    Export(#[from] ts_rs::ExportError),
    /// File system error.
    #[error("io: {0}")]
    Io(#[from] io::Error),
    /// `--check` found differences.
    #[error("generated TypeScript is out of date: {0:?}. Run `cargo run -p fc-api --bin gen-ts`.")]
    OutOfDate(Vec<String>),
}

fn config(out_dir: &Path) -> Config {
    Config::new().with_large_int("number").with_out_dir(out_dir)
}

/// Generates all files into `dir` (which should be empty).
pub fn generate_into(dir: &Path) -> Result<(), GenError> {
    fs::create_dir_all(dir)?;
    let cfg = config(dir);
    for m in &public_catalog() {
        (m.export_ts)(&cfg)?;
    }
    // Roots not reachable from method signatures.
    crate::envelope::InvokeRequest::export_all(&cfg)?;
    crate::envelope::InvokeResponse::export_all(&cfg)?;
    crate::error::ErrorCategory::export_all(&cfg)?;
    v1::events::EventEnvelope::export_all(&cfg)?;
    crate::method::MethodKind::export_all(&cfg)?;
    // Job results (`JobDto.result`) of the io module.
    v1::io::ImportReport::export_all(&cfg)?;
    v1::io::ExportReport::export_all(&cfg)?;
    v1::io::RestoreReport::export_all(&cfg)?;
    // Job result of the optimizer (v0.6).
    v1::planning::OptimizerResult::export_all(&cfg)?;
    // Job result of the ai module (`ai.request`).
    v1::ai::AiJobResult::export_all(&cfg)?;
    // Job results of provider setup (`ai.models`, `ai.test`).
    v1::ai::AiModelList::export_all(&cfg)?;
    v1::ai::AiConnectionTest::export_all(&cfg)?;
    v1::ai::AiSourceText::export_all(&cfg)?;
    // Job result of `reading.clip` (v0.10; `reading.import` returns a ReadingItemDto).
    v1::reading::ReadingClip::export_all(&cfg)?;
    // Local HTTP API transport DTOs (v0.9, for the browser extension).
    v1::local_api::export_http_types(&cfg)?;
    // Subtitle extension contract (v1.2, `/subtitle/v1/*`).
    v1::subtitle::export_http_types(&cfg)?;

    fs::write(dir.join("methods.ts"), methods_ts(&cfg))?;
    let files = list_ts_files(dir)?;
    fs::write(dir.join("index.ts"), index_ts(&files))?;
    Ok(())
}

fn header() -> &'static str {
    "// This file was generated by `cargo run -p fc-api --bin gen-ts`. Do not edit this file manually.\n"
}

/// Methods a client may call. Internal ones (undo inverses) are not part of the frontend's
/// typed surface; transports reject them.
fn public_catalog() -> Vec<crate::MethodDescriptor> {
    v1::catalog()
        .into_iter()
        .filter(|m| m.visibility == crate::Visibility::Public)
        .collect()
}

fn methods_ts(cfg: &Config) -> String {
    let catalog = public_catalog();
    let mut types = BTreeSet::new();
    for m in &catalog {
        types.insert((m.request_ts)(cfg));
        types.insert((m.response_ts)(cfg));
    }
    let mut out = String::from(header());
    for t in &types {
        out.push_str(&format!("import type {{ {t} }} from \"./{t}\";\n"));
    }
    out.push_str(&format!(
        "\n/** API version prefix of qualified method names (`{v}.decks.create`). */\nexport const API_VERSION = \"{v}\" as const;\n\n",
        v = crate::API_VERSION
    ));
    out.push_str("/** Every v1 method: kind, request params and response type. */\nexport interface Methods {\n");
    for m in &catalog {
        let kind = match m.kind {
            MethodKind::Command => "command",
            MethodKind::Query => "query",
        };
        out.push_str(&format!(
            "  \"{}\": {{ kind: \"{}\"; request: {}; response: {} }};\n",
            m.name,
            kind,
            (m.request_ts)(cfg),
            (m.response_ts)(cfg)
        ));
    }
    out.push_str("}\n\n");
    out.push_str("/** Unqualified method name. */\nexport type MethodName = keyof Methods;\n");
    out.push_str("/** Request params of method `M`. */\nexport type RequestOf<M extends MethodName> = Methods[M][\"request\"];\n");
    out.push_str("/** Response of method `M`. */\nexport type ResponseOf<M extends MethodName> = Methods[M][\"response\"];\n");
    out.push_str("/** Names of command methods. */\nexport type CommandName = { [K in MethodName]: Methods[K][\"kind\"] extends \"command\" ? K : never }[MethodName];\n");
    out.push_str("/** Names of query methods. */\nexport type QueryName = { [K in MethodName]: Methods[K][\"kind\"] extends \"query\" ? K : never }[MethodName];\n\n");
    out.push_str("/** Runtime list of method names and kinds. */\nexport const METHODS: { readonly [K in MethodName]: Methods[K][\"kind\"] } = {\n");
    for m in &catalog {
        let kind = match m.kind {
            MethodKind::Command => "command",
            MethodKind::Query => "query",
        };
        out.push_str(&format!("  \"{}\": \"{}\",\n", m.name, kind));
    }
    out.push_str("};\n");
    out
}

fn index_ts(files: &[String]) -> String {
    let mut out = String::from(header());
    for f in files {
        if f == "index.ts" {
            continue;
        }
        let module = f.trim_end_matches(".ts");
        if module == "methods" {
            out.push_str("export * from \"./methods\";\n");
        } else {
            out.push_str(&format!("export type * from \"./{module}\";\n"));
        }
    }
    out
}

/// Relative paths (with `/`) of all `.ts` files under `dir`, sorted.
fn list_ts_files(dir: &Path) -> io::Result<Vec<String>> {
    fn walk(base: &Path, dir: &Path, out: &mut Vec<String>) -> io::Result<()> {
        for entry in fs::read_dir(dir)? {
            let path = entry?.path();
            if path.is_dir() {
                walk(base, &path, out)?;
            } else if path.extension().is_some_and(|e| e == "ts") {
                if let Ok(rel) = path.strip_prefix(base) {
                    out.push(rel.to_string_lossy().replace('\\', "/"));
                }
            }
        }
        Ok(())
    }
    let mut out = Vec::new();
    if dir.exists() {
        walk(dir, dir, &mut out)?;
    }
    out.sort();
    Ok(out)
}

fn staging_dir() -> PathBuf {
    let unique = format!(
        "fc-gen-ts-{}-{:?}",
        std::process::id(),
        std::thread::current().id()
    )
    .replace(['(', ')'], "");
    std::env::temp_dir().join(unique)
}

/// Regenerates `out_dir`: removes stale `.ts` files, writes fresh ones. Returns the files
/// written.
pub fn write(out_dir: &Path) -> Result<Vec<String>, GenError> {
    let staging = staging_dir();
    let _ = fs::remove_dir_all(&staging);
    generate_into(&staging)?;
    for old in list_ts_files(out_dir)? {
        fs::remove_file(out_dir.join(&old))?;
    }
    let files = list_ts_files(&staging)?;
    for f in &files {
        let dest = out_dir.join(f);
        if let Some(parent) = dest.parent() {
            fs::create_dir_all(parent)?;
        }
        fs::copy(staging.join(f), dest)?;
    }
    let _ = fs::remove_dir_all(&staging);
    Ok(files)
}

/// Compares `out_dir` with a fresh generation. `Ok(())` if identical.
pub fn check(out_dir: &Path) -> Result<(), GenError> {
    let staging = staging_dir();
    let _ = fs::remove_dir_all(&staging);
    generate_into(&staging)?;
    let fresh = list_ts_files(&staging)?;
    let existing = list_ts_files(out_dir)?;
    let mut diffs = Vec::new();
    for f in fresh.iter().chain(existing.iter()).collect::<BTreeSet<_>>() {
        if HAND_WRITTEN.contains(&f.as_str()) {
            continue;
        }
        let a = fs::read(staging.join(f)).ok();
        let b = fs::read(out_dir.join(f)).ok();
        if a != b {
            diffs.push(f.clone());
        }
    }
    let _ = fs::remove_dir_all(&staging);
    if diffs.is_empty() {
        Ok(())
    } else {
        Err(GenError::OutOfDate(diffs))
    }
}
