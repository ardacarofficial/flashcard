/**
 * Icon keys the backend sends in `UiContribution.icon` (fc-app `main_menu(…, icon, …)`) and
 * plugin manifests may use. Unknown keys fall back to `fallback`.
 */
const BY_KEY: Record<string, IconNode> = {
  home: House,
  study: GraduationCap,
  learn: Repeat,
  test: ClipboardCheck,
  match: Shuffle,
  decks: Library,
  library: Library,
  sliders: SlidersHorizontal,
  plus: Plus,
  list: List,
  inbox: Inbox,
  search: Search,
  chart: BarChart3,
  calendar: Calendar,
  target: Target,
  sparkles: Sparkles,
  'book-open': BookOpen,
  layers: Layers,
  io: ArrowLeftRight,
  plug: Plug,
  zap: Zap,
  wrench: Wrench,
  puzzle: Puzzle,
  keyboard: Keyboard,
  lifebuoy: LifeBuoy,
  bell: Bell,
  users: Users,
  link: Link,
  settings: Settings,
  palette: Palette,
  data: Database,
  lock: Lock,
};

export function iconFor(key: string | null | undefined, fallback: IconNode = FileText): IconNode {
  return (key && BY_KEY[key]) || fallback;
}

